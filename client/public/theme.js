// Disarm and eliminate "Powered by Netlify" sign / HUD overlay
(function () {
  try {
    var kill = function (n) {
      if (!n || n.nodeType !== 1) return;
      if (n.tagName === 'SCRIPT' && ((n.src && n.src.indexOf('/.netlify/scripts/hud') !== -1) || n.hasAttribute('data-nf-variant'))) {
        try {
          n.removeAttribute('data-nf-variant');
          if (n.dataset) delete n.dataset.nfVariant;
          n.src = '';
          n.remove();
        } catch (e) {}
      }
      if (n.tagName === 'IFRAME' && (n.id === 'nl-badge-frame' || n.id === 'nl-hud-frame' || /Netlify/i.test(n.title || '') || /Netlify/i.test(n.getAttribute('title') || ''))) {
        try { n.remove(); } catch (e) {}
      }
    };
    var obs = new MutationObserver(function (mutations) {
      for (var i = 0; i < mutations.length; i++) {
        var added = mutations[i].addedNodes;
        for (var j = 0; j < added.length; j++) kill(added[j]);
      }
    });
    obs.observe(document.documentElement, { childList: true, subtree: true });
    var cleanup = function () {
      try {
        var frames = document.querySelectorAll('iframe#nl-badge-frame, iframe#nl-hud-frame, iframe[title*="Netlify" i], script[data-nf-variant]');
        for (var i = 0; i < frames.length; i++) frames[i].remove();
      } catch (e) {}
    };
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', cleanup);
    } else {
      cleanup();
    }
    window.addEventListener('load', cleanup);
  } catch (e) {}
})();

// Applies the saved appearance (light/dark) and colour theme before first paint, so there is no flash.
// The theme CSS itself is generated by src/theme/engine.js and cached in localStorage.
// Nothing saved → the store's default (cached from Admin → Settings → Appearance) → light + Default.
(function () {
  try {
    var d = document.documentElement;
    // One-time reset (Oct 2026): dark became the default, so drop light/dark picks saved before then.
    if (localStorage.getItem('wt-mode-reset') !== '1') {
      localStorage.removeItem('wt-theme');
      localStorage.setItem('wt-mode-reset', '1');
    }
    var site = JSON.parse(localStorage.getItem('wt-site-appearance') || 'null') || {};
    var mode = localStorage.getItem('wt-theme') || site.defaultMode || 'dark';
    if (mode === 'system') mode = matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
    if (mode === 'light') d.dataset.theme = 'light';
    else d.dataset.theme = 'dark';
    if (localStorage.getItem('wt-contrast') === 'high') d.dataset.contrast = 'high';
    // Vision settings (text size, readable font, link underlines, motion): see src/theme/engine.js applyVision.
    var v = JSON.parse(localStorage.getItem('wt-vision') || 'null') || {};
    if (v.textSize === 'small' || v.textSize === 'large' || v.textSize === 'xl') d.dataset.textSize = v.textSize;
    if (v.corners === 'sharp' || v.corners === 'soft' || v.corners === 'round') d.dataset.corners = v.corners;
    if (v.underlineLinks) d.dataset.underlineLinks = 'on';
    if (v.reduceMotion) d.dataset.reduceMotion = 'on';
    if (v.readableFont) {
      d.dataset.readableFont = 'on';
      var rf = document.createElement('link');
      rf.rel = 'stylesheet';
      rf.href = 'https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@500;700;800&display=swap';
      document.head.appendChild(rf);
    }
    var css = JSON.parse(localStorage.getItem('wt-theme-css') || 'null');
    // If cached theme was the old clear theme default and not deliberately chosen by user, ignore it so default applies
    if (css && css.id === 'clear' && !localStorage.getItem('wt-palette')) css = null;
    if (css && css[mode]) {
      var s = document.createElement('style');
      s.id = 'wt-theme-vars';
      s.textContent = css[mode];
      document.head.appendChild(s);
    }
    if (css && css.id) d.dataset.palette = css.id;
    if (css && css.design) d.dataset.design = css.design;    if (css && css.font) {
      var l = document.createElement('link');
      l.rel = 'stylesheet';
      l.href = css.font;
      document.head.appendChild(l);
    }
  } catch (e) {}
})();
